"""Stage 2a — replay the G0-V5 discovery trajectories and persist per-step state.

Protocol: docs/c2-qualification-preregistration.md
Frozen criteria: artifacts/c2_qualification/C2_QUALIFICATION_FROZEN.json

This consumes NO fresh seeds. It replays the ORIGINAL discovery block
(9400000-9400029) with the ORIGINAL frozen 1M checkpoints, on the same map,
ruleset, opponents and horizon. The policies are deterministic, so the
trajectories are the same ones the G0-V5 discovery already analysed. The only
new thing is that per-step state is persisted, which the original run never did
-- precursor_windows.csv kept only aggregates over one fixed 30-decision window
ending at each failure, so lag bands cannot be recovered from it.

HOW DRIFT IS MADE IMPOSSIBLE
----------------------------
Trajectories are not regenerated by a reimplemented loop. This module calls the
ORIGINAL ``run_g0_v2_evaluation.run_eval_episode`` unchanged and captures its
``steps`` and ``failure_events`` by temporarily wrapping
``run_g0_v2_evaluation.summarize_episode``, which already receives both. There
is therefore no second copy of the episode loop that could diverge.

THE REPLAY-EQUIVALENCE GATE
---------------------------
Persisting the right rows is not enough; they must reconstruct the frozen
discovery. This module rebuilds the [-30, 0) windows from the replayed steps
using the ORIGINAL ``build_windows``/``window_features`` and compares every row
against artifacts/g0_v5_evaluation/precursor_windows.csv:

    same window keys, same opportunity flags, same support counts,
    same feature values within serialization tolerance

If that fails, the lag audit MUST NOT run: a mismatch means the replay is not
the same experiment, and any lag result would describe different trajectories.
The gate writes its verdict and returns non-zero.

Run:  python experiments/run_c2_step_replay.py
"""
from __future__ import annotations

import argparse
import csv
import json
import math
import sys
import time
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

import torch  # noqa: E402

import experiments.run_g0_v2_evaluation as E  # noqa: E402

# The ORIGINAL G0-V5 discovery block. Not a fresh block.
REPLAY_SEED_BASE = 9_400_000
EPISODES_PER_CELL = 30
G0_SEEDS = (3_200_001, 3_200_002, 3_200_003)

OUT_DIR = PROJECT_ROOT / "artifacts" / "c2_qualification"
FROZEN_WINDOWS = PROJECT_ROOT / "artifacts" / "g0_v5_evaluation" / "precursor_windows.csv"

# Feature comparison tolerance. The frozen CSV was written from Python floats
# via csv.DictWriter, so values round-trip through repr(); anything beyond this
# is a real difference, not formatting.
FEATURE_TOL = 1e-9

# Derived per-step features named in the frozen audit list. Both are computable
# from legal_context alone, so no extra environment access is needed.
def _derived(ctx: dict) -> dict:
    mate = ctx.get("escort_distance", float("nan"))
    defd = ctx.get("nearest_ready_defender", float("nan"))
    bad = (
        mate is None or defd is None
        or (isinstance(mate, float) and (math.isnan(mate) or math.isinf(mate)))
        or (isinstance(defd, float) and (math.isnan(defd) or math.isinf(defd)))
    )
    if bad:
        return {"intervention_margin": float("nan"), "mate_can_intervene": float("nan")}
    return {
        "intervention_margin": float(defd) - float(mate),
        "mate_can_intervene": float(float(mate) <= float(defd)),
    }


def _artifact_dir(seed: int) -> Path:
    return PROJECT_ROOT / "artifacts" / "g0_v5_long" / f"g0_v5_long_seed{seed}"


def _run_tag(seed: int) -> str:
    return f"g0_v5_long_seed{seed}"


def load_policy_for(seed: int, device: str):
    from rl.custom_ppo.checkpoints.loader import read_checkpoint_payload
    from rl.evaluation.checkpoint import load_policy
    from rl.ruleset_identity import ARTIFACT_IDENTITY_KEY

    tag = _run_tag(seed)
    ckpt = _artifact_dir(seed) / "ckpts" / f"final_{tag}.zip"
    payload = read_checkpoint_payload(str(ckpt), map_location="cpu")
    ai = payload.get(ARTIFACT_IDENTITY_KEY, {})
    if str(ai.get("ruleset_id")) != E.RULESET_ID:
        raise ValueError(f"{ckpt}: ruleset mismatch")
    if int(payload.get("global_step", 0)) < 1_000_000:
        raise ValueError(f"{ckpt}: not the preregistered 1M checkpoint")
    channels = E.resolve_cnn_channels(payload, context=str(ckpt))
    return load_policy(str(ckpt), device=device, num_cnn_channels=channels)


def replay(device: str, episodes: int, seeds: list[int]) -> tuple[list[dict], list[dict]]:
    """-> (per-step rows, rebuilt [-30,0) window rows)."""
    step_rows: list[dict] = []
    rebuilt: list[dict] = []

    real_summarize = E.summarize_episode
    captured: dict = {}

    def capture(steps, **kw):
        captured["steps"] = steps
        captured["failure_events"] = kw.get("failure_events") or []
        return real_summarize(steps, **kw)

    E.summarize_episode = capture
    try:
        for pseed in seeds:
            policy = load_policy_for(pseed, device)
            for opp in E.OPPONENTS:
                for i in range(episodes):
                    ev = REPLAY_SEED_BASE + i
                    captured.clear()
                    E.run_eval_episode(policy, opponent=opp, seed=ev, device=device)
                    steps = captured["steps"]
                    fev = captured["failure_events"]
                    ekey = f"{opp}:{ev}"

                    fail_at: dict[int, list[str]] = {}
                    for label, t in fev:
                        fail_at.setdefault(int(t), []).append(label)

                    for t, ctx in enumerate(steps):
                        row = {
                            "policy_seed": pseed, "opponent": opp, "eval_seed": ev,
                            "episode_key": ekey, "step_i": t,
                            "score_stratum": (
                                "leading" if ctx["score_diff"] > 0
                                else "trailing" if ctx["score_diff"] < 0 else "tied"
                            ),
                            "failure_labels_at_t": "|".join(sorted(fail_at.get(t, []))),
                        }
                        for k, v in ctx.items():
                            row[k] = float(v) if isinstance(v, bool) else v
                        row.update(_derived(ctx))
                        step_rows.append(row)

                    # Rebuild the frozen windows with the ORIGINAL function.
                    for w in E.build_windows(steps, fev, episode_key=ekey):
                        rebuilt.append({
                            "train_seed": pseed, "opponent": opp, "eval_seed": ev, **w
                        })
                print(f"  seed {pseed} vs {opp}: {episodes} episodes replayed", flush=True)
    finally:
        E.summarize_episode = real_summarize
    return step_rows, rebuilt


def _key(r: dict) -> tuple:
    return (
        int(r["train_seed"]), str(r["opponent"]), int(r["eval_seed"]),
        str(r["kind"]), str(r["failure_label"]),
        int(r["window_start"]), int(r["window_end"]),
    )


# Schema-aware comparison. Casting everything to float would silently equate a
# boolean flag with a count, and would turn every 'True' vs True into a
# mismatch. Each column is parsed as the type window_features() actually
# produces.
BOOL_COLS = frozenset({
    "opp_has_carrier", "opp_home_threatened", "opp_leading",
    "carrier_pressure_increasing",
})
INT_COLS = frozenset({"window_len", "max_agents_forward"})
STR_COLS = frozenset({"episode_key"})


def _as_bool(v):
    if isinstance(v, bool):
        return v
    if isinstance(v, str):
        s = v.strip()
        if s in ("True", "False"):
            return s == "True"
        if s in ("1", "1.0"):
            return True
        if s in ("0", "0.0"):
            return False
    if isinstance(v, (int, float)) and not (isinstance(v, float) and math.isnan(v)):
        return bool(v)
    return None


def _as_float(v):
    if v is None or v == "":
        return None
    if isinstance(v, bool):
        return float(v)
    if isinstance(v, str) and v.strip().lower() in ("nan", "none", ""):
        return float("nan")
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def _cells_equal(col: str, a, b) -> tuple[bool, object, object]:
    """-> (equal, normalised_frozen, normalised_replayed)."""
    if col in STR_COLS:
        return (str(a) == str(b), str(a), str(b))
    if col in BOOL_COLS:
        pa, pb = _as_bool(a), _as_bool(b)
        return (pa is not None and pa == pb, pa, pb)
    if col in INT_COLS:
        fa, fb = _as_float(a), _as_float(b)
        if fa is None or fb is None:
            return (fa == fb, fa, fb)
        return (int(fa) == int(fb), int(fa), int(fb))
    fa, fb = _as_float(a), _as_float(b)
    if fa is None or fb is None:
        return (fa == fb, fa, fb)
    if math.isnan(fa) or math.isnan(fb):
        return (math.isnan(fa) and math.isnan(fb), fa, fb)
    return (abs(fa - fb) <= FEATURE_TOL, fa, fb)


def _json_safe(o):
    """NaN/Inf are not valid JSON; the report must stay parseable."""
    if isinstance(o, dict):
        return {k: _json_safe(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [_json_safe(v) for v in o]
    if isinstance(o, float) and (math.isnan(o) or math.isinf(o)):
        return None
    return o


def equivalence_gate(rebuilt: list[dict], *, full_run: bool) -> dict:
    """Rebuilt [-30,0) windows must match the frozen discovery CSV.

    ``full_run`` is True only when all three policies and all 30 episodes per
    cell were replayed. On a partial smoke run the frozen CSV legitimately
    contains windows the replay never generated, so missing keys are reported
    but do not fail the gate; extra keys and value mismatches always do.
    """
    if not FROZEN_WINDOWS.is_file():
        return {"PASS": False, "error": f"missing frozen reference: {FROZEN_WINDOWS}"}

    with open(FROZEN_WINDOWS, newline="", encoding="utf-8") as f:
        frozen = list(csv.DictReader(f))
    feat_cols = [c for c in frozen[0]
                 if c not in ("train_seed", "opponent", "eval_seed", "kind",
                              "failure_label", "window_start", "window_end",
                              "episode_key")]

    # Scope the frozen reference to the population actually replayed. A partial
    # run must still prove exactness on its own subset -- comparing 14 episodes
    # against the full 630-episode artifact would report 5,527 spurious
    # "missing" rows and hide whether the subset itself was reproduced.
    replayed_cells = {
        (int(r["train_seed"]), str(r["opponent"]), int(r["eval_seed"]))
        for r in rebuilt
    }
    frozen_scoped = [
        r for r in frozen
        if (int(r["train_seed"]), str(r["opponent"]), int(r["eval_seed"])) in replayed_cells
    ]

    fmap = {_key(r): r for r in frozen_scoped}
    rmap = {_key(r): r for r in rebuilt}

    missing = sorted(set(fmap) - set(rmap))
    extra = sorted(set(rmap) - set(fmap))
    mismatches: list[dict] = []
    compared = 0
    for k in sorted(set(fmap) & set(rmap)):
        a, b = fmap[k], rmap[k]
        for c in feat_cols:
            eq, na, nb = _cells_equal(c, a.get(c), b.get(c))
            compared += 1
            if not eq and len(mismatches) < 50:
                mismatches.append({"key": list(k), "column": c,
                                   "frozen": na, "replayed": nb})

    dup_frozen = len(frozen_scoped) - len(fmap)
    dup_replay = len(rebuilt) - len(rmap)

    # Missing is now enforced ALWAYS: the reference is scoped to what was
    # actually replayed, so a partial run has no excuse for a gap.
    ok = not missing and not extra and not mismatches
    return {
        "PASS": bool(ok),
        "full_run": bool(full_run),
        "missing_enforced": True,
        "scoped_to_replayed_population": True,
        "duplicate_keys_frozen": dup_frozen,
        "duplicate_keys_replay": dup_replay,
        "duplicate_note": (
            "Two failure events sharing a label and step collapse to one key on "
            "both sides equally, so duplicates are reported rather than compared."
        ),
        "frozen_reference": str(FROZEN_WINDOWS.relative_to(PROJECT_ROOT)),
        "n_frozen_windows_total": len(frozen),
        "n_frozen_windows_in_replayed_scope": len(frozen_scoped),
        "n_rebuilt_windows": len(rebuilt),
        "n_keys_matched": len(set(fmap) & set(rmap)),
        "n_missing_in_replay": len(missing),
        "n_extra_in_replay": len(extra),
        "n_feature_values_compared": compared,
        "n_mismatches": len(mismatches),
        "first_missing": [list(k) for k in missing[:5]],
        "first_extra": [list(k) for k in extra[:5]],
        "first_mismatches": mismatches[:10],
        "tolerance": FEATURE_TOL,
        "meaning_if_failed": (
            "The replay is NOT the same experiment as the frozen discovery. The "
            "lag audit must not run, because any result would describe different "
            "trajectories than the ones C2 qualification is defined against."
        ),
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--episodes", type=int, default=EPISODES_PER_CELL)
    ap.add_argument("--device", default="cuda" if torch.cuda.is_available() else "cpu")
    ap.add_argument("--seeds", type=int, nargs="*", default=list(G0_SEEDS))
    args = ap.parse_args()

    # Point the frozen harness at the G0-V5 checkpoints and the ORIGINAL block.
    E.artifact_dir_for = _artifact_dir
    E.run_tag_for = _run_tag
    E.EVAL_SEED_BASE = REPLAY_SEED_BASE

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    started = time.time()
    print("=" * 78)
    print("C2 STAGE 2a — REPLAY of the G0-V5 discovery trajectories")
    print(f"seeds={args.seeds}  opponents={E.OPPONENTS}  episodes/cell={args.episodes}")
    print(f"ORIGINAL discovery block {REPLAY_SEED_BASE}..{REPLAY_SEED_BASE + args.episodes - 1}")
    print("no fresh seeds consumed; trajectories are deterministic replays")
    print("=" * 78)

    step_rows, rebuilt = replay(args.device, args.episodes, args.seeds)

    if step_rows:
        with open(OUT_DIR / "C2_STEP_REPLAY.csv", "w", encoding="utf-8", newline="") as f:
            w = csv.DictWriter(f, fieldnames=list(step_rows[0].keys()))
            w.writeheader()
            w.writerows(step_rows)

    full_run = (
        int(args.episodes) == EPISODES_PER_CELL
        and sorted(args.seeds) == sorted(G0_SEEDS)
    )
    gate = equivalence_gate(rebuilt, full_run=full_run)
    gate["generated_utc"] = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    gate["replay_seed_base"] = REPLAY_SEED_BASE
    gate["episodes_per_cell"] = args.episodes
    gate["policy_seeds"] = list(args.seeds)
    gate["n_step_rows"] = len(step_rows)
    gate["wall_seconds"] = round(time.time() - started, 1)
    (OUT_DIR / "C2_REPLAY_EQUIVALENCE.json").write_text(
        json.dumps(_json_safe(gate), indent=2, default=str, allow_nan=False),
        encoding="utf-8")

    print("\n" + "=" * 78)
    print(f"step rows persisted : {len(step_rows):,}")
    print(f"windows rebuilt     : {len(rebuilt):,}  "
          f"(frozen in scope: {gate['n_frozen_windows_in_replayed_scope']:,} "
          f"of {gate['n_frozen_windows_total']:,})")
    print(f"duplicate keys      : frozen={gate['duplicate_keys_frozen']} replay={gate['duplicate_keys_replay']}")
    print(f"keys matched        : {gate['n_keys_matched']:,}")
    print(f"missing / extra     : {gate['n_missing_in_replay']} / {gate['n_extra_in_replay']}")
    print(f"values compared     : {gate['n_feature_values_compared']:,}  mismatches: {gate['n_mismatches']}")
    print(f"\nREPLAY EQUIVALENCE: {'PASS' if gate['PASS'] else 'FAIL'}")
    if not gate["PASS"]:
        print("STOP — the lag audit must not run until this is explained.")
        for m in gate["first_mismatches"][:3]:
            print(f"  {m}")
    print("=" * 78)
    return 0 if gate["PASS"] else 5


if __name__ == "__main__":
    raise SystemExit(main())
