"""SAPPO V1 — collect anchor demonstrations from the projected validated teachers.

Frozen protocol: artifacts/strategic_demand/STRATEGY_ANCHORED_PPO_V1_FROZEN.json

Produces, for each specialist, a dataset of (observation, PPO-waypoint action)
pairs generated by the projected teacher for that pole:

    pi_A anchor  <-  pole A  +  projected GUARD
    pi_B anchor  <-  pole B  +  projected BREACH

No opposite-style examples are collected. The opposite projected controllers
existed only to make the representability probe apples-to-apples; SAPPO's job is
pi_A <- GUARD and pi_B <- BREACH.

Two properties this file exists to get right
--------------------------------------------
1. LABELS ONLY AT DECISION POINTS. The engine latches a macro action only when
   blue_commit_ticks_left <= 0; on every other step the issued action is ignored.
   Supervision must therefore exist only where the policy actually had a choice,
   or the dataset is dominated by locked-in steps and the anchor objective
   degenerates into "keep doing what you are already committed to".

2. THE LABEL IS THE PROJECTED ACTION, NOT THE TEACHER'S RAW TARGET. The scripted
   teacher writes continuous (x, y); PPO emits (macro, waypoint_idx). The label
   is the teacher's target snapped to the nearest of the 50 macro waypoints,
   which is exactly the action the representability probe showed preserves the
   strategic ordering (+0.406 on A, +0.562 on B).

Seeds are training-only and disjoint from every evaluation block. A fixed 90/10
train/diagnostic split is written at collection time; the 10% split measures
teacher-action agreement only and is NOT a strategic gate.

Run:  python experiments/sappo_collect_demonstrations.py --device cuda --episodes 64
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import torch

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import experiments.r2_learned_crossover as R2                      # noqa: E402
from experiments.opponent_spec import (                            # noqa: E402
    assert_live_opponent_batch, install_keyed_opponent_overlays, pole_A_genome,
)
from experiments.sappo_teacher_representability import (           # noqa: E402
    GUARD, BREACH, TEACHER_FOR,
)
from rl.curriculum import phase_from_tag                           # noqa: E402

# Training-only demonstration block. Disjoint from 7800001..7800192 (SAPPO eval),
# 7500001..7500192 (R2, spent), and 7900001+ (representability probe).
DEMO_SEED_BASE = 8_000_001
OUT_DIR = ROOT / "artifacts/strategic_demand/sappo_demonstrations"
TRAIN_FRAC = 0.90


def _now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def collect_episode(pole: str, seed: int, device: str) -> dict:
    """Roll the projected teacher; record labels ONLY at macro-decision points."""
    from macro_actions import MacroAction

    style = TEACHER_FOR[pole]
    base_key = R2.POLES[pole]
    genomes = {"OP6": pole_A_genome()} if pole == "A" else {}

    env = R2.build_env(device, seed)
    core = env.core
    try:
        core._bt_profile_override = None
        core._sds_opening_hold_steps = 0
        install_keyed_opponent_overlays(core, genomes)
        env.env_method("set_phase", phase_from_tag(base_key))
        env.env_method("set_next_opponent", "SCRIPTED", base_key)
        obs = env.reset()
        assert_live_opponent_batch(core, genomes, allowed_keys=(base_key,),
                                   context=f"demo {pole} seed {seed}")
        core.blue_scripted = True
        core.set_blue_style(style)
        wp = core._macro_targets

        obs_rows, act_rows, decision_flags = [], [], []
        n_steps = n_decisions = 0
        for _ in range(R2.MAX_STEPS):
            # Is a macro decision available THIS step, per agent?
            avail = (core.blue_commit_ticks_left[0] <= 0)

            tx, ty = core._assign_blue_style_targets()
            t = torch.stack([tx[0], ty[0]], dim=-1)
            d = torch.cdist(t.unsqueeze(0).float(), wp.unsqueeze(0).float())[0]
            idx = torch.argmin(d, dim=-1)
            carrying = core.blue_carrying[0]
            macro = torch.where(carrying,
                                torch.full_like(idx, int(MacroAction.GO_HOME)),
                                torch.full_like(idx, int(MacroAction.GO_TO)))
            act = torch.stack([macro, idx], dim=-1)          # [Nb, 2]

            if bool(avail.any().item()):
                # Store the observation once, with a per-agent mask of which
                # agents were actually choosing.
                obs_rows.append({k: np.asarray(v).copy() for k, v in obs.items()}
                                if isinstance(obs, dict) else np.asarray(obs).copy())
                act_rows.append(act.detach().cpu().numpy().copy())
                decision_flags.append(avail.detach().cpu().numpy().copy())
                n_decisions += int(avail.sum().item())

            core.blue_scripted = False
            env.step_async(act.reshape(-1).cpu().numpy().astype(np.int64))
            obs, _r, done, _info = env.step_wait()
            core.blue_scripted = True
            n_steps += 1
            if bool(np.asarray(done).any()):
                break

        return {"obs": obs_rows, "act": act_rows, "mask": decision_flags,
                "n_steps": n_steps, "n_decision_labels": n_decisions,
                "n_decision_steps": len(act_rows)}
    finally:
        env.close()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--device", default="cuda")
    ap.add_argument("--episodes", type=int, default=64,
                    help="demonstration episodes per pole")
    a = ap.parse_args()

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    print(f"SAPPO DEMONSTRATION COLLECTION  {_now()}")
    print(f"  seeds {DEMO_SEED_BASE}..{DEMO_SEED_BASE + a.episodes - 1} (training-only)")
    print(f"  labels ONLY at macro-decision points (blue_commit_ticks_left <= 0)")

    manifest = {"record": "SAPPO V1 anchor demonstrations", "utc": _now(),
                "protocol": "artifacts/strategic_demand/STRATEGY_ANCHORED_PPO_V1_FROZEN.json",
                "seed_base": DEMO_SEED_BASE, "episodes_per_pole": a.episodes,
                "label_rule": "blue_commit_ticks_left <= 0",
                "label_is": "projected teacher action (macro, nearest-of-50 waypoint)",
                "train_frac": TRAIN_FRAC, "poles": {}}

    for pole, teacher in (("A", GUARD), ("B", BREACH)):
        eps = []
        tot_steps = tot_labels = tot_dsteps = 0
        for i in range(a.episodes):
            e = collect_episode(pole, DEMO_SEED_BASE + i, a.device)
            eps.append(e)
            tot_steps += e["n_steps"]
            tot_labels += e["n_decision_labels"]
            tot_dsteps += e["n_decision_steps"]
            if (i + 1) % 8 == 0:
                print(f"  pole {pole}: {i+1}/{a.episodes} episodes, "
                      f"{tot_labels} labels", flush=True)

        # Fixed 90/10 split by EPISODE, decided before any training.
        rng = np.random.default_rng(7)
        order = rng.permutation(len(eps))
        n_train = int(round(TRAIN_FRAC * len(eps)))
        train_idx, diag_idx = sorted(order[:n_train]), sorted(order[n_train:])

        def pack(idxs):
            if not idxs:
                return {}, np.zeros((0, 2, 2)), np.zeros((0, 2))
            acts = np.concatenate([eps[i]["act"] for i in idxs], axis=0)
            masks = np.concatenate([eps[i]["mask"] for i in idxs], axis=0)
            # Observations are the whole point of the dataset: the anchor loss is
            # -log pi(a_teacher | o), so an actions-only file is unusable.
            keys = eps[idxs[0]]["obs"][0].keys()
            obs = {k: np.concatenate(
                [np.concatenate([step[k] for step in eps[i]["obs"]], axis=0)
                 for i in idxs], axis=0) for k in keys}
            return obs, acts, masks

        tr_o, tr_a, tr_m = pack(train_idx)
        dg_o, dg_a, dg_m = pack(diag_idx)
        np.savez_compressed(OUT_DIR / f"anchor_{pole}_train.npz",
                            actions=tr_a, decision_mask=tr_m,
                            episode_ids=np.array(train_idx),
                            **{f"obs_{k}": v for k, v in tr_o.items()})
        np.savez_compressed(OUT_DIR / f"anchor_{pole}_diagnostic.npz",
                            actions=dg_a, decision_mask=dg_m,
                            episode_ids=np.array(diag_idx),
                            **{f"obs_{k}": v for k, v in dg_o.items()})

        manifest["poles"][pole] = {
            "teacher_style": teacher,
            "episodes": a.episodes,
            "total_env_steps": tot_steps,
            "decision_steps": tot_dsteps,
            "agent_labels": tot_labels,
            "label_density": round(tot_dsteps / max(1, tot_steps), 4),
            "train_episodes": len(train_idx),
            "diagnostic_episodes": len(diag_idx),
        }
        print(f"  pole {pole}: {tot_dsteps}/{tot_steps} steps were decision points "
              f"({tot_dsteps/max(1,tot_steps):.1%}), {tot_labels} agent labels")

    txt = json.dumps(manifest, indent=2)
    manifest["manifest_sha256"] = hashlib.sha256(txt.encode()).hexdigest()[:16]
    (OUT_DIR / "manifest.json").write_text(json.dumps(manifest, indent=2),
                                           encoding="utf-8")
    print(f"\nwritten: {OUT_DIR}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
